#!/usr/bin/env python3
"""gen_vectors.py SFD OUT.c IMPL.c [IMPL.c ...]: ACNet bsdsocket.library's vector table,
from the published bsdsocket_lib.sfd (NDK 3.2, SANA+RoadshowTCP-IP), and
beside it bsdsocket_protos.h, every bsd_<name> prototype, which the IMPL files
include so the compiler holds it to the SFD's types.

Each library vector becomes a wrapper that takes the SFD's registers and
calls bsd_<name>(base, args...) in the IMPL files with ordinary C arguments. A vector
no IMPL file defines gets a stub that sets ENOSYS and fails. ==varargs
entries share the slot before them; ==reserve N adds N empty slots. The SFD
is read at build time, so nothing from the NDK is kept in git and no offset is
typed by hand.
"""
import os
import re
import sys


def parse(path):
    """[(slot kind, entry)] in LVO order from the bias; entry = (ret, name, [(type, name)], [regs])."""
    lines, cur = [], ""
    for raw in open(path, encoding="latin-1"):
        line = raw.split("*", 1)[0] if raw.lstrip().startswith("*") else raw
        line = line.rstrip()
        if not line.strip():
            continue
        if cur:
            cur += " " + line.strip()
        else:
            cur = line.strip()
        if cur.startswith("==") or re.search(r"\)\s*\([^)]*\)\s*$", cur):
            lines.append(cur)
            cur = ""
    slots, bias, varargs, includes = [], None, False, []
    for line in lines:
        if line.startswith("=="):
            word = line[2:].split()
            if word[0] == "bias":
                bias = int(word[1])
            elif word[0] == "reserve":
                slots += [("reserved", None)] * int(word[1])
            elif word[0] == "varargs":
                varargs = True
            elif word[0] == "include":
                includes.append(word[1])
            continue
        m = re.match(r"(.*?)\b(\w+)\s*\((.*)\)\s*\(([^)]*)\)\s*$", line)
        if not m:
            raise SystemExit(f"cannot read SFD line: {line}")
        ret, name, params, regs = m.group(1).strip(), m.group(2), m.group(3).strip(), m.group(4)
        if varargs:                      # the varargs twin of the line before: no slot of its own
            varargs = False
            continue
        regs = [r.strip().lower() for r in regs.split(",") if r.strip()]
        args = []
        if params and params != "void":
            for p in params.split(","):
                p = p.strip()
                pm = re.match(r"(.*?)(\w+)\s*$", p)
                args.append((pm.group(1).strip(), pm.group(2)))
        if len(args) != len(regs):
            raise SystemExit(f"{name}: {len(args)} arguments, {len(regs)} registers")
        slots.append(("function", (ret, name, args, regs)))
    if bias != 30:
        raise SystemExit(f"unexpected bias {bias}")
    return slots, includes


def failure(ret):
    """What a vector the library lacks returns."""
    if ret == "VOID":
        return None
    if "*" in ret or ret in ("STRPTR", "APTR", "BOOL"):
        return "0"
    return "-1"


def main():
    sfd, out, impls = sys.argv[1], sys.argv[2], sys.argv[3:]
    slots, includes = parse(sfd)
    have = set()
    for impl in impls:
        have |= set(re.findall(r"^\w[\w\s\*]*?\bbsd_(\w+)\s*\(", open(impl, encoding="latin-1").read(), re.M))
    head = ["/* Generated by gen_vectors.py from bsdsocket_lib.sfd: do not edit. */",
            "#include \"acnet_lib.h\""]
    head += [f"#include {i}" for i in includes if i not in ("<exec/lists.h>",)]
    protos = head[:1] + ["#ifndef BSDSOCKET_PROTOS_H", "#define BSDSOCKET_PROTOS_H"] + head[1:] + [""]
    for kind, entry in slots:
        if kind == "function":
            ret, name, args, _regs = entry
            protos.append(f"{ret} bsd_{name}(" + ", ".join(["struct SocketBase *sb"] + [f"{t} {n}" for t, n in args]) + ");")
    protos.append("#endif")
    open(os.path.join(os.path.dirname(out) or ".", "bsdsocket_protos.h"), "w").write("\n".join(protos) + "\n")
    w = head[:1] + ["#include \"bsdsocket_protos.h\"", ""]
    table = []
    done = 0
    for kind, entry in slots:
        if kind == "reserved":
            table.append("(APTR)lib_reserved")
            continue
        ret, name, args, regs = entry
        params = ", ".join([f"REG({r}, {t} {n})" for (t, n), r in zip(args, regs)] + ["REG(a6, struct SocketBase *sb)"])
        call_args = ", ".join(["sb"] + [n for _, n in args])
        if name in have:
            body = f"bsd_{name}({call_args});" if ret == "VOID" else f"return bsd_{name}({call_args});"
            done += 1
        else:
            fail = failure(ret)
            body = "lib_unimplemented(sb);" + ("" if fail is None else f" return ({ret}){fail};")
            body += "".join(f" (void){n};" for _, n in args)
        w.append(f"static {ret} LIB_{name}({params}) {{ {body} }}")
        table.append(f"(APTR)LIB_{name}")
    w.append("")
    w.append("const APTR acnet_vectors[] = {")
    w.append("    (APTR)lib_open, (APTR)lib_close, (APTR)lib_expunge, (APTR)lib_reserved,")
    for i in range(0, len(table), 4):
        w.append("    " + ", ".join(table[i:i + 4]) + ",")
    w.append("    (APTR)-1")
    w.append("};")
    w.append(f"/* {len(table)} vectors after the four standard ones; {done} implemented. */")
    open(out, "w").write("\n".join(w) + "\n")
    print(f"{out}: {len(table)} vectors, {done} implemented, {len(table) - done - sum(1 for k, _ in slots if k == 'reserved')} stubs")


if __name__ == "__main__":
    main()
